#!/usr/bin/env python3
"""LuxOS - Nastaveni > Firemni sit (luxos-domain-settings) se zastupnym lux-domain a pomocnikem.

    env -u DISPLAY xvfb-run -a dbus-run-session -- python3 packages/luxos-domain/tests/gui-settings.py [--shots DIR]

Nic skutecneho se nespousti (zadny pkexec, realm, adcli): LUXOS_DOMAIN_CLI a LUXOS_DOMAIN_HELPER_CMD
ukazuji na skripty v tests/fake-gui, ktere zapisuji argumenty a stdin do docasneho calls.log.
Overuje: hledani domeny (popis, chyba DNS, rozdil hodin + Nastavit hodiny), pripojeni (heslo jen na
stdin, nikdy v argumentech ani prostredi, kroky prubehu), chybne heslo, stranku Pripojeno, spravce,
offline dny, odpojeni (s odebranim uctu i bez), viditelnou horni listu se zaviracim tlacitkem.
"""
import argparse
import json
import os
import sys
import tempfile
import time
from importlib.machinery import SourceFileLoader
# Jen virtualni X z xvfb-run (nebo vyslovne LUXOS_TEST_X=1 ve VM) - nikdy skutecna obrazovka
if "xvfb-run" not in os.environ.get("XAUTHORITY", "") and os.environ.get("LUXOS_TEST_X") != "1":
    sys.exit("Run under xvfb-run (or LUXOS_TEST_X=1 in a VM) - never on a real display.")

ap = argparse.ArgumentParser()
ap.add_argument("--shots", help="directory for screenshots (default: temp dir)")
opts = ap.parse_args()
SHOTS = opts.shots or tempfile.mkdtemp(prefix="luxos-domain-shots-")
os.makedirs(SHOTS, exist_ok=True)

HERE = os.path.dirname(os.path.abspath(__file__))
FAKE = os.path.join(HERE, "fake-gui")
DIR = tempfile.mkdtemp(prefix="luxos-domain-gui-")
RESOLV = os.path.join(DIR, "resolv.conf")
with open(RESOLV, "w") as f:
    f.write("# Generated by NetworkManager\nsearch firma.local\nnameserver 10.0.0.1\n")
os.environ.update({"LANG": "en_US.UTF-8", "FAKE_DOMAIN_DIR": DIR, "LUXOS_DOMAIN_RESOLV": RESOLV,
                   "LUXOS_DOMAIN_CLI": os.path.join(FAKE, "lux-domain"),
                   "LUXOS_DOMAIN_HELPER_CMD": f"{sys.executable} {os.path.join(FAKE, 'helper')}"})
s = SourceFileLoader("luxos_domain_settings",
                     os.path.join(HERE, "..", "files", "luxos-domain-settings")).load_module()
from gi.repository import Gdk, Gtk  # noqa: E402

FAILS = []
SECRET = "secret"


def check(desc, cond, extra=""):
    print(("ok    " if cond else "FAIL  ") + desc + (f"\n      {extra}" if extra and not cond else ""))
    if not cond:
        FAILS.append(desc)


def pump(sec=0.0):
    end = time.monotonic() + sec
    while True:
        while Gtk.events_pending():
            Gtk.main_iteration_do(False)
        if time.monotonic() >= end:
            break
        time.sleep(0.01)


def wait(cond, sec=8.0):
    end = time.monotonic() + sec
    while time.monotonic() < end:
        pump(0.03)
        if cond():
            return True
    return False


def calls():
    try:
        with open(os.path.join(DIR, "calls.log"), encoding="utf-8") as f:
            return f.read().splitlines()
    except OSError:
        return []


def helper_calls():
    return [c for c in calls() if c.startswith("helper ")]


def shot(win, name):
    pump(0.3)
    w = win.get_window()
    pb = Gdk.pixbuf_get_from_window(w, 0, 0, w.get_width(), w.get_height()) if w else None
    if pb:
        pb.savev(os.path.join(SHOTS, name + ".png"), "png", [], [])
    return pb is not None


def new_window():
    win = s.DomainWindow()
    win.show_all()
    check("window loads a page", wait(lambda: win.page_name != "loading"), win.page_name)
    return win


def visible_text(widget):
    out = []

    def walk(w):
        if isinstance(w, Gtk.Label) and w.get_visible() and w.get_mapped():
            out.append(w.get_text())
        if isinstance(w, Gtk.Container):
            for c in w.get_children():
                walk(c)
    walk(widget)
    return "\n".join(out)


# ---- ciste funkce ----
check("parse_line step", s.parse_line("@@STEP 2 5 Creating the account\n") == ("step", "Creating the account", 2, 5))
check("parse_line error with text", s.parse_line("@@ERROR password Wrong.") == ("error", "password", "Wrong."))
check("parse_line error without text", s.parse_line("@@ERROR clock") == ("error", "clock", ""))
check("parse_line done", s.parse_line("@@DONE") == ("done",))
check("error_text fallback", "5 minutes" in s.error_text("clock"))
check("error_text helper text wins", s.error_text("password", "X") == "X")
check("describe", s.describe({"domain": "firma.local", "controllers": ["a", "b"]})
      == "Microsoft Active Directory – firma.local – 2 controllers")
check("search_domain from resolv.conf", s.search_domain(RESOLV) == "firma.local")
check("valid_domain", s.valid_domain("firma.local") and not s.valid_domain("firma") and not s.valid_domain("a b.cz"))

# ---- neni v domene: hledani ----
win = new_window()
check("not joined -> join page", win.page_name == "join")
hb = win.get_titlebar()
check("title bar visible with close button", hb is not None and hb.get_visible() and hb.get_show_close_button())
check("domain prefilled from DHCP search", win.domain_entry.get_text() == "firma.local")
check("join disabled without user and password", not win.join_btn.get_sensitive())
win.find()
check("discover finished", wait(lambda: win.busy_op is None and win.found.get_text()
                                and "Looking" not in win.found.get_text()))
check("discover describes the domain", "firma.local – 2 controllers" in win.found.get_text(), win.found.get_text())
check("no clock button when in sync", not win.clock_btn.get_visible())
check("screenshot join", shot(win, "settings-join"))

win.domain_entry.set_text("nowhere.example")
win.find()
wait(lambda: win.busy_op is None and "Looking" not in win.found.get_text())
check("discover error shown as human text", "could not be found" in win.found.get_text(), win.found.get_text())

win.domain_entry.set_text("skew.local")
win.find()
wait(lambda: win.busy_op is None and "Looking" not in win.found.get_text())
check("clock skew warning", "5 minutes" in win.found.get_text() and win.clock_btn.get_visible(), win.found.get_text())
win.sync_time()
check("sync-time via helper", wait(lambda: "matches the domain" in win.found.get_text()), win.found.get_text())
check("sync-time helper call", any('["sync-time"]' in c for c in helper_calls()), helper_calls())

# ---- chybne heslo ----
win.domain_entry.set_text("firma.local")
win.user_entry.set_text("admin")
win.pw_entry.set_text("badpw")
check("join enabled", win.join_btn.get_sensitive())
win.join()
check("password field cleared at once", win.pw_entry.get_text() == "")
check("bad password reported", wait(lambda: "wrong (from helper)" in win.result.get_text()), win.result.get_text())
check("still on join page", win.page_name == "join")

# ---- chyba hodin z join: tlacitko Nastavit hodiny ----
win.pw_entry.set_text("clock")
win.join()
check("clock error offers sync", wait(lambda: win.busy_op is None and win.clock_btn.get_visible()
                                       and "5 minutes" in win.result.get_text()), win.result.get_text())

# ---- uspesne pripojeni ----
steps = []
orig = win.on_progress
win.on_progress = lambda item: (steps.append(item), orig(item))[1]
win.pw_entry.set_text(SECRET)
win.ou_entry.set_text("OU=PCs,DC=firma,DC=local")
win.admins_entry.set_text("LuxOS Admins")
win.join()
check("join -> joined page", wait(lambda: win.page_name == "joined", 10), win.page_name)
check("progress steps received", [x[2] for x in steps if x[0] == "step"] == [1, 2, 3, 4], steps)
joins = [c for c in helper_calls() if c.startswith('helper ["join"')]
last = joins[-1] if joins else ""
check("helper join argv has domain, user, OU but no password",
      last.startswith('helper ["join", "firma.local", "admin", "OU=PCs,DC=firma,DC=local"]') and SECRET not in
      last.split(" env-has-secret")[0], last)
check("password only on helper stdin", 'stdin="secret\\n"' in last, last)
check("password not in helper environment", "env-has-secret=False" in last, last)
check("password not in any CLI call", not any(SECRET in c for c in calls() if c.startswith("cli ")))
check("extra admin group added after join", any('["admins-add", "LuxOS Admins"]' in c for c in helper_calls()))
txt = visible_text(win)
check("joined page shows domain and status", "firma.local" in txt and "Connected" in txt, txt)
check("joined message", "Log out and sign in" in txt, txt)
check("joined shows both admin groups", "Domain Admins" in txt and "LuxOS Admins" in txt, txt)
check("screenshot joined", shot(win, "settings-joined"))

# ---- spravci a offline dny ----
win.admin_entry.set_text("IT")
win.admins("admins-add", "IT")
check("admins add reloads", wait(lambda: win.busy_op is None and "IT" in visible_text(win)))
win.offline_spin.set_value(14)
win.set_offline_days()
check("offline days via helper", wait(lambda: any('["set-offline-days", "14"]' in c for c in helper_calls())))
check("offline days reloaded", wait(lambda: win.busy_op is None and win.offline_spin.get_value() == 14))
win.destroy()
pump(0.1)

# ---- offline stav a pozastavena prava ----
with open(os.path.join(DIR, "status.json")) as f:
    st = json.load(f)
st.update(online=False, offline_left_days=9, last_online="2026-10-20T08:00:00+01:00", admins_active=False)
with open(os.path.join(DIR, "status.json"), "w") as f:
    json.dump(st, f)
win = new_window()
txt = visible_text(win)
check("offline shown", "Offline" in txt and "Last contact" in txt, txt)
check("offline days left shown", "9 more days" in txt, txt)
check("admin rights suspended shown", "Suspended" in txt, txt)
check("screenshot offline", shot(win, "settings-offline"))

# ---- odpojeni: dialog, bez jmena a hesla neodejde, pak s odebranim uctu ----
d = win.leave_dialog()
pump(0.2)
dtxt = visible_text(d)
check("leave dialog explains personal files stay", "not deleted" in dtxt, dtxt)
check("leave dialog has a title bar", d.get_titlebar() is not None and d.get_titlebar().get_visible())
check("screenshot leave dialog", shot(d, "settings-leave"))
d.remove_check.set_active(True)
n = len(helper_calls())
d.response(Gtk.ResponseType.OK)
pump(0.2)
check("remove account without credentials keeps the dialog", d.get_visible() and len(helper_calls()) == n)
d.user.set_text("admin")
d.pw.set_text(SECRET)
d.response(Gtk.ResponseType.OK)
check("leave -> join page", wait(lambda: win.page_name == "join", 10), win.page_name)
leave = [c for c in helper_calls() if c.startswith('helper ["leave"')][-1]
check("leave with account removal: user in argv, password on stdin only",
      leave.startswith('helper ["leave", "admin"]') and 'stdin="secret\\n"' in leave, leave)
win.destroy()
pump(0.1)

# ---- odpojeni bez odebrani uctu ----
with open(os.path.join(DIR, "status.json"), "w") as f:
    json.dump(dict(st, online=True, admins_active=True), f)
win = new_window()
win.leave()
check("plain leave", wait(lambda: win.page_name == "join", 10))
leave = [c for c in helper_calls() if c.startswith('helper ["leave"')][-1]
check("plain leave: no user, empty stdin", leave.startswith('helper ["leave"]') and 'stdin=""' in leave, leave)
win.destroy()
pump(0.1)

# ---- lux-domain chybi: stranka pripojeni s hlaskou, bez padu ----
s.CLI = "/nonexistent/lux-domain"
win = new_window()
check("missing CLI -> join page with message", win.page_name == "join" and win.result.get_visible(),
      win.result.get_text())
win.destroy()
pump(0.1)

print(f"\nscreenshots: {SHOTS}")
print(f"\n{len(FAILS)} failure(s)" if FAILS else "\nall ok")
sys.exit(1 if FAILS else 0)
